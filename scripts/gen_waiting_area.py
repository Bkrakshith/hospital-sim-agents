#!/usr/bin/env python3
"""Write config/waiting_area.yaml (seats and landmarks) from hospital-sim-humans/sim/lobby_chairs.py.

Run: python scripts/gen_waiting_area.py
"""
import importlib.util
import math
import os
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
HG1_ROOT = Path(os.environ.get("HG1_ROOT", HERE.parents[1]))
CHAIRS = HG1_ROOT / "hospital-sim-humans" / "sim" / "lobby_chairs.py"
OUT = HERE.parent / "config" / "waiting_area.yaml"

SEAT_OFFSET_M = 0.30  # seat centre distance from the front edge of the row

LANDMARKS = {
    "reception_g1": (1.05, 1.62, "Reception desk, where the G1 stands"),
    "reception_front": (1.00, 0.57, "In front of the reception desk"),
    "entrance": (-1.24, -2.30, "Main entrance"),
    "clinic_corridor": (5.60, 5.40, "Corridor to the outpatient clinics"),
    "ward_doors": (11.20, 7.25, "Doors to the wards and lifts"),
    "toilets": (-11.50, 1.20, "Toilets (placeholder position)"),
    "nurse_call_point": (5.60, 3.00, "Where a nurse is called from (placeholder position)"),
}


def load_chairs():
    spec = importlib.util.spec_from_file_location("lobby_chairs", CHAIRS)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def build(lc):
    seats = []
    for r, (name, box) in enumerate(lc.ROWS.items()):
        x0, y0, _, x1, y1, _ = box
        south = name in lc.FACES_SOUTH
        for k in range(len(lc.ARM_X) - 1):
            mid = (lc.ARM_X[k] + lc.ARM_X[k + 1]) / 2
            seats.append({
                "id": f"{'ABCD'[r]}{k + 1}",
                "x": round(x0 + mid if south else x1 - mid, 3),
                "y": round(y0 + SEAT_OFFSET_M if south else y1 - SEAT_OFFSET_M, 3),
                "yaw": round(-math.pi / 2 if south else math.pi / 2, 4),
                "row": name,
            })
    return {
        "seats": seats,
        "landmarks": {k: {"x": x, "y": y, "label": label} for k, (x, y, label) in LANDMARKS.items()},
        "entrance": "entrance",
        "exits": ["entrance", "clinic_corridor", "ward_doors"],
        "nurse_call_point": "nurse_call_point",
    }


def main():
    data = build(load_chairs())
    OUT.parent.mkdir(parents=True, exist_ok=True)
    header = "# Generated by scripts/gen_waiting_area.py from hospital-sim-humans/sim/lobby_chairs.py. Do not edit.\n"
    OUT.write_text(header + yaml.safe_dump(data, sort_keys=False))
    print(f"wrote {OUT} ({len(data['seats'])} seats)")


if __name__ == "__main__":
    main()
