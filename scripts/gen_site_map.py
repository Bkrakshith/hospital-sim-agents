def subtract(lo, hi, cuts):
    """Pieces of [lo, hi] left after removing each (a, b) in cuts."""
    pieces = [(lo, hi)]
    for a, b in cuts:
        a, b = min(a, b), max(a, b)
        nxt = []
        for p, q in pieces:
            if b <= p or a >= q:
                nxt.append((p, q))
                continue
            if a > p:
                nxt.append((p, a))
            if b < q:
                nxt.append((b, q))
        pieces = nxt
    return [(p, q) for p, q in pieces if q - p > 0.05]


def build_walls(L, boxes, rooms, doors):
    walls = []
    for b in boxes["boxes"]:
        if b["cat"] != "building_wall":
            continue
        x0, y0, _, x1, y1, _ = b["box"]
        if x1 - x0 >= y1 - y0:
            y = (y0 + y1) / 2
            walls.append([x0, y, x1, y])
        else:
            x = (x0 + x1) / 2
            walls.append([x, y0, x, y1])
    # compartment and other screens, minus their openings
    for s in L["BUILDING_SCREENS"].values():
        x0, y0, x1, y1 = s["line"]
        if abs(x1 - x0) < 1e-6:
            for p, q in subtract(min(y0, y1), max(y0, y1), [(a, b) for a, b, _ in s["openings"]]):
                walls.append([x0, p, x0, q])
        else:
            for p, q in subtract(min(x0, x1), max(x0, x1), [(a, b) for a, b, _ in s["openings"]]):
                walls.append([p, y0, q, y0])
    # the wing is built from kit modules: draw its room edges minus the doorways and openings
    ox, oy, _ = L["WING_ORIGIN"]
    cuts = [[d["a"], d["b"]] for d in doors if d["id"].startswith("Wing_")]
    cuts += [[[x0 + ox, y0 + oy], [x1 + ox, y1 + oy]] for x0, y0, x1, y1 in L["OPENINGS"]]
    seen = set()
    for r in rooms:
        if r["compartment"] != "Wing":
            continue
        poly = r["poly"]
        for i in range(4):
            (x0, y0), (x1, y1) = poly[i], poly[(i + 1) % 4]
            horiz = abs(y1 - y0) < 1e-6
            c = y0 if horiz else x0
            lo, hi = (min(x0, x1), max(x0, x1)) if horiz else (min(y0, y1), max(y0, y1))
            key = (horiz, round(c, 3), round(lo, 3), round(hi, 3))
            if key in seen:
                continue
            seen.add(key)
            hit = []
            for a, b in cuts:
                if horiz and abs(a[1] - c) < 0.05 and abs(b[1] - c) < 0.05:
                    hit.append((a[0], b[0]))
                if not horiz and abs(a[0] - c) < 0.05 and abs(b[0] - c) < 0.05:
                    hit.append((a[1], b[1]))
            for p, q in subtract(lo, hi, hit):
                walls.append([p, c, q, c] if horiz else [c, p, c, q])
    return [[r3(v) for v in w] for w in walls]


# ------------------------------------------------------------------ occupancy grid
def read_pgm(path):
    raw = Path(path).read_bytes()
    m = re.match(rb"P5\s+(?:#[^\n]*\n\s*)*(\d+)\s+(\d+)\s+(\d+)\s", raw)
    w, h = int(m.group(1)), int(m.group(2))
    return np.frombuffer(raw[m.end():m.end() + w * h], np.uint8).reshape(h, w)


def grid_from_pgm():
    img = read_pgm(PGM)[::-1]  # row 0 = south edge, like origin
    blocked = (img < 128).astype(np.uint8)  # negate 0: dark is occupied
    f = int(round(RES / PGM_RES))
    h, w = blocked.shape
    ph, pw = -h % f, -w % f
    blocked = np.pad(blocked, ((0, ph), (0, pw)))
    occ = blocked.reshape(blocked.shape[0] // f, f, blocked.shape[1] // f, f).max(axis=(1, 3))
    return occ.astype(np.uint8), RES, np.array(PGM_ORIGIN, dtype=float)


def grid_from_npz(path):
    d = np.load(path)
    return d["occ"].astype(np.uint8), float(d["res"]), np.asarray(d["origin"], dtype=float)


def to_cell(occ_res_origin, x, y):
    occ, res, origin = occ_res_origin
    return int(math.floor((y - origin[1]) / res)), int(math.floor((x - origin[0]) / res))


def carve(grid, segs):
    occ, res, origin = grid
    for (x0, y0), (x1, y1) in segs:
        dx, dy = x1 - x0, y1 - y0
        n2 = dx * dx + dy * dy
        xs0, xs1 = min(x0, x1) - DOOR_HALF_WIDTH, max(x0, x1) + DOOR_HALF_WIDTH
        ys0, ys1 = min(y0, y1) - DOOR_HALF_WIDTH, max(y0, y1) + DOOR_HALF_WIDTH
        ix0, iy0 = to_cell(grid, xs0, ys0)[1], to_cell(grid, xs0, ys0)[0]
        ix1, iy1 = to_cell(grid, xs1, ys1)[1], to_cell(grid, xs1, ys1)[0]
        for iy in range(max(iy0, 0), min(iy1, occ.shape[0] - 1) + 1):
            for ix in range(max(ix0, 0), min(ix1, occ.shape[1] - 1) + 1):
                cx, cy = origin[0] + (ix + 0.5) * res, origin[1] + (iy + 0.5) * res
                t = 0.0 if n2 == 0 else max(0.0, min(1.0, ((cx - x0) * dx + (cy - y0) * dy) / n2))
                if math.hypot(cx - (x0 + t * dx), cy - (y0 + t * dy)) <= DOOR_HALF_WIDTH:
                    occ[iy, ix] = 0


def clear_disc(grid, x, y, radius=0.3):
    occ, res, origin = grid
    iy0, ix0 = to_cell(grid, x - radius, y - radius)
    iy1, ix1 = to_cell(grid, x + radius, y + radius)
    for iy in range(max(iy0, 0), min(iy1, occ.shape[0] - 1) + 1):
        for ix in range(max(ix0, 0), min(ix1, occ.shape[1] - 1) + 1):
            cx, cy = origin[0] + (ix + 0.5) * res, origin[1] + (iy + 0.5) * res
            if math.hypot(cx - x, cy - y) <= radius:
                occ[iy, ix] = 0


def free_point_near(grid, poly, x, y):
    """Free cell centre inside poly (with a free 3x3 neighbourhood if possible) nearest to (x, y)."""
    occ, res, origin = grid
    xs = [p[0] for p in poly]
    ys = [p[1] for p in poly]
    iy0, ix0 = to_cell(grid, min(xs), min(ys))
    iy1, ix1 = to_cell(grid, max(xs), max(ys))
    best = {}
    for iy in range(max(iy0, 1), min(iy1, occ.shape[0] - 2) + 1):
        for ix in range(max(ix0, 1), min(ix1, occ.shape[1] - 2) + 1):
            if occ[iy, ix]:
                continue
            cx, cy = origin[0] + (ix + 0.5) * res, origin[1] + (iy + 0.5) * res
            if not point_in_poly(poly, cx, cy):
                continue
            d = math.hypot(cx - x, cy - y)
            tier = 0 if not occ[iy - 1:iy + 2, ix - 1:ix + 2].any() else 1
            if tier not in best or d < best[tier][0]:
                best[tier] = (d, cx, cy)
    for tier in (0, 1):
        if tier in best:
            return best[tier][1], best[tier][2]
    return None


